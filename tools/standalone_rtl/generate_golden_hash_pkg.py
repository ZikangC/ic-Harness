#!/usr/bin/env python3
"""Emit synthesizable FNV-1a descriptor-name constants for golden RTL."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from reference import ModelConfig, fnv1a64, matmul_shapes, small_params  # noqa: E402


def ident(name: str) -> str:
    return "H_" + name.upper().replace(".", "_")


def main() -> None:
    output = Path(sys.argv[1]) if len(sys.argv) == 2 else ROOT / "standalone_rtl/rtl/golden_name_hash_pkg.sv"
    cfg = ModelConfig()
    names = ["emb.q", "emb.s", "emb.z"]
    for name in matmul_shapes(cfg):
        names += [name + ".q", name + ".s", name + ".z"]
    names += [name for name, _ in small_params(cfg)]
    lines = ["// Generated by tools/generate_golden_hash_pkg.py; do not hand-edit.",
             "package golden_name_hash_pkg;"]
    for name in names:
        lines.append(f"  localparam logic [31:0] {ident(name)} = 32'h{fnv1a64(name) & 0xffffffff:08x}; // {name}")
    lines.append("endpackage")
    output.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(names)} FNV descriptor constants to {output}")

    meta_out = output.with_name("golden_tensor_meta_pkg.sv")
    meta = ["// Generated alongside golden_name_hash_pkg.sv; do not hand-edit.",
            "package golden_tensor_meta_pkg;", "  import golden_name_hash_pkg::*;",
            "  typedef struct packed {logic [31:0] q_hash,s_hash,z_hash; logic [31:0] q_bytes,s_bytes,z_bytes;} qsz_meta_t;",
            "  function automatic qsz_meta_t matrix_meta(input logic [7:0] id, input logic group_is_128);", "    qsz_meta_t m; begin m='0; case (id)"]
    for index, (name, (fan_in, fan_out)) in enumerate(matmul_shapes(cfg).items()):
        groups = (fan_in + min(cfg.group_size, fan_in) - 1) // min(cfg.group_size, fan_in)
        groups64 = (fan_in + min(64, fan_in) - 1) // min(64, fan_in)
        meta += [f"      8'd{index}: begin m.q_hash={ident(name+'.q')}; m.s_hash={ident(name+'.s')}; m.z_hash={ident(name+'.z')};",
                 f"        m.q_bytes=32'd{fan_in*fan_out//2}; m.s_bytes=32'd{groups*fan_out*2}; m.z_bytes=32'd{groups*fan_out};" +
                 (f" if (!group_is_128) begin m.s_bytes=32'd{groups64*fan_out*2}; m.z_bytes=32'd{groups64*fan_out}; end" if groups64 != groups else "") + " end"]
    meta += ["      default: ; endcase matrix_meta=m; end endfunction", "endpackage"]
    meta_out.write_text("\n".join(meta) + "\n")
    print(f"wrote matrix metadata to {meta_out}")


if __name__ == "__main__":
    main()
