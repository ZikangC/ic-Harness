// Shared descriptor/DMA front end for the independent decoder top.
//
// Descriptor hashes use a deliberately documented, synthesizable ABI rather
// than any private implementation: matrix tensors are
//   0x4d00_0000 | (op_code<<13) | (tensor_id<<5) | (expert<<2) | qsz_section
// and small tensors are 0x5300_0000 | (op_code<<3) | sub_index.
// The image packer must put those values in descriptor.name_hash.  Keeping the
// mapping here makes the descriptor lookup and the DMA data path observable.
module weight_stream_frontend #(
  parameter int DATA_W = 24
) (
  input logic clk, input logic rst_n,
  input logic [35:0] descriptor_base, input logic [31:0] descriptor_count,
  input logic [35:0] tokens_base,

  // Token word client (nano_compute_fabric READ_TOKEN phase).
  input logic token_req_valid, input logic [31:0] token_index,
  output logic token_req_done, output logic [8:0] token_id,

  // Small parameter client (nano_compute_fabric FETCH_WEIGHTS phase).
  input logic small_job_valid, input logic [4:0] small_job_op,
  output logic small_job_done,
  output logic signed [64*16-1:0] norm_offset_bus,
  output logic signed [64*4*16-1:0] kda_q_taps_bus,
  output logic signed [64*4*16-1:0] kda_k_taps_bus,
  output logic signed [64*4*16-1:0] kda_v_taps_bus,
  output logic signed [8*DATA_W-1:0] moe_bias_bus,
  output logic signed [DATA_W-1:0] residual_score0,
  output logic signed [DATA_W-1:0] residual_score1,

  // q/s/z client (nano_datapath_adapter EXECUTE phase).
  input logic matrix_req_valid, input logic [4:0] matrix_op_code,
  input logic [7:0] matrix_tensor_id, input logic [2:0] matrix_expert_index,
  input logic [15:0] matrix_q_beats, input logic [15:0] matrix_s_beats,
  input logic [15:0] matrix_z_beats, output logic matrix_req_accept,
  output logic matrix_dma_valid, input logic matrix_dma_ready,
  output logic [1:0] matrix_dma_section, output logic [127:0] matrix_dma_data,

  output logic error,

  // Two clients of mem_arbiter4: descriptor reads (m1) and data DMA (m2).
  output logic desc_mem_req_valid, input logic desc_mem_req_ready,
  output logic [35:0] desc_mem_req_addr, input logic desc_mem_rsp_valid,
  output logic desc_mem_rsp_ready, input logic [127:0] desc_mem_rsp_rdata,
  output logic dma_mem_req_valid, input logic dma_mem_req_ready,
  output logic [35:0] dma_mem_req_addr, input logic dma_mem_rsp_valid,
  output logic dma_mem_rsp_ready, input logic [127:0] dma_mem_rsp_rdata
);
  localparam logic [4:0]
    OP_L0_NORM1=5'd1, OP_L0_KDA=5'd2, OP_L0_RESMIX=5'd3,
    OP_L0_NORM2=5'd4, OP_L0_MOE=5'd5, OP_L1_RESA=5'd6,
    OP_L1_NORM1=5'd7, OP_L1_RESMIX=5'd9, OP_L1_NORM2=5'd10,
    OP_L1_MOE=5'd11, OP_OUT_RESMIX=5'd12, OP_FINAL_NORM=5'd13;
  typedef enum logic [3:0] {IDLE, TOKEN_DMA_START, TOKEN_STREAM, TOKEN_DONE,
    LOOKUP_START, LOOKUP_WAIT, DMA_START, SMALL_STREAM, MATRIX_STREAM,
    NEXT_SMALL, SMALL_DONE, FAIL} state_t;
  state_t state;
  logic active_is_matrix;
  logic [4:0] active_op;
  logic [7:0] active_tensor;
  logic [2:0] active_expert;
  logic [1:0] active_section;
  logic [15:0] active_q_beats, active_s_beats, active_z_beats;
  logic [2:0] small_sub;
  logic [5:0] small_beat;
  logic [31:0] active_token_index;
  logic [35:0] dma_base;
  logic [31:0] dma_bytes;
  logic [31:0] wanted_hash;
  logic [31:0] expected_bytes;
  logic [35:0] active_token_byte_addr;

  logic desc_start, desc_busy, desc_found, desc_failed;
  logic [35:0] desc_tensor_addr;
  logic [31:0] desc_tensor_bytes, desc_tensor_aux;
  logic dma_start, dma_busy, dma_done, dma_data_valid, dma_data_ready, dma_data_last;
  logic [127:0] dma_data;
  integer lane;

  function automatic logic [2:0] small_sub_count(input logic [4:0] op);
    case (op)
      OP_L0_KDA: small_sub_count = 3;
      OP_L0_NORM1, OP_L0_RESMIX, OP_L0_NORM2, OP_L0_MOE,
      OP_L1_RESA, OP_L1_NORM1, OP_L1_RESMIX, OP_L1_NORM2,
      OP_L1_MOE, OP_OUT_RESMIX, OP_FINAL_NORM: small_sub_count = 1;
      default: small_sub_count = 0;
    endcase
  endfunction
  function automatic logic [31:0] matrix_byte_count(input logic [1:0] section,
                                                       input logic [15:0] qb,
                                                       input logic [15:0] sb,
                                                       input logic [15:0] zb);
    case (section)
      2'd0: matrix_byte_count = {12'd0,qb} << 4;
      2'd1: matrix_byte_count = {12'd0,sb} << 4;
      default: matrix_byte_count = {12'd0,zb} << 4;
    endcase
  endfunction

  // No string processing occurs in hardware; these are fixed descriptor ABI
  // fields and can be generated by an image packer without RTL knowledge.
  always_comb begin
    active_token_byte_addr = tokens_base + ({4'd0,active_token_index} << 2);
    if (active_is_matrix)
      wanted_hash = 32'h4d00_0000 | ({27'd0,active_op} << 13) |
                    ({24'd0,active_tensor} << 5) |
                    ({29'd0,active_expert} << 2) | active_section;
    else
      wanted_hash = 32'h5300_0000 | ({27'd0,active_op} << 3) | small_sub;
    expected_bytes = active_is_matrix ? matrix_byte_count(active_section, active_q_beats, active_s_beats, active_z_beats) : 32'd0;
  end

  descriptor_lookup descriptors (
    .clk, .rst_n, .start(desc_start), .descriptor_base, .descriptor_count,
    .wanted_name_hash(wanted_hash), .busy(desc_busy), .found(desc_found), .failed(desc_failed),
    .tensor_addr(desc_tensor_addr), .tensor_bytes(desc_tensor_bytes), .tensor_aux(desc_tensor_aux),
    .mem_req_valid(desc_mem_req_valid), .mem_req_ready(desc_mem_req_ready), .mem_req_addr(desc_mem_req_addr),
    .mem_rsp_valid(desc_mem_rsp_valid), .mem_rsp_ready(desc_mem_rsp_ready), .mem_rsp_rdata(desc_mem_rsp_rdata)
  );
  dma_read16 dma (
    .clk, .rst_n, .start(dma_start), .base_addr(dma_base), .byte_count(dma_bytes),
    .busy(dma_busy), .done(dma_done), .mem_req_valid(dma_mem_req_valid), .mem_req_ready(dma_mem_req_ready),
    .mem_req_addr(dma_mem_req_addr), .mem_rsp_valid(dma_mem_rsp_valid), .mem_rsp_ready(dma_mem_rsp_ready),
    .mem_rsp_rdata(dma_mem_rsp_rdata), .data_valid(dma_data_valid), .data_ready(dma_data_ready),
    .data(dma_data), .data_last(dma_data_last)
  );

  always_comb begin
    desc_start = (state == LOOKUP_START);
    dma_start = (state == TOKEN_DMA_START) || (state == DMA_START);
    token_req_done = (state == TOKEN_DONE);
    small_job_done = (state == SMALL_DONE);
    matrix_req_accept = (state == IDLE) && matrix_req_valid && !token_req_valid && !small_job_valid;
    matrix_dma_valid = (state == MATRIX_STREAM) && dma_data_valid;
    matrix_dma_data = dma_data;
    matrix_dma_section = active_section;
    if (state == MATRIX_STREAM)
      dma_data_ready = matrix_dma_ready;
    else
      dma_data_ready = (state == TOKEN_STREAM) || (state == SMALL_STREAM);
  end

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      state <= IDLE; error <= 1'b0; active_is_matrix <= 1'b0; active_op <= '0;
      active_tensor <= '0; active_expert <= '0; active_section <= '0;
      active_q_beats <= '0; active_s_beats <= '0; active_z_beats <= '0;
      small_sub <= '0; small_beat <= '0; active_token_index <= '0;
      dma_base <= '0; dma_bytes <= '0; token_id <= '0;
      norm_offset_bus <= '0; kda_q_taps_bus <= '0; kda_k_taps_bus <= '0; kda_v_taps_bus <= '0;
      moe_bias_bus <= '0; residual_score0 <= '0; residual_score1 <= '0;
    end else begin
      case (state)
        IDLE: begin
          if (token_req_valid) begin
            active_token_index <= token_index;
            // One aligned 16B read contains four uint32 token ids.
            dma_base <= (tokens_base + ({4'd0,token_index} << 2)) & 36'hffff_ffff0;
            dma_bytes <= 32'd16;
            state <= TOKEN_DMA_START;
          end else if (small_job_valid) begin
            active_is_matrix <= 1'b0; active_op <= small_job_op; small_sub <= '0; small_beat <= '0;
            case (small_job_op)
              OP_L0_KDA: begin kda_q_taps_bus <= '0; kda_k_taps_bus <= '0; kda_v_taps_bus <= '0; end
              OP_L0_NORM1, OP_L0_NORM2, OP_L1_NORM1, OP_L1_NORM2, OP_FINAL_NORM: norm_offset_bus <= '0;
              OP_L0_MOE, OP_L1_MOE: moe_bias_bus <= '0;
              OP_L0_RESMIX, OP_L1_RESA, OP_L1_RESMIX, OP_OUT_RESMIX: begin residual_score0 <= '0; residual_score1 <= '0; end
              default: ;
            endcase
            if (small_sub_count(small_job_op) == 0) state <= SMALL_DONE;
            else state <= LOOKUP_START;
          end else if (matrix_req_accept) begin
            active_is_matrix <= 1'b1; active_op <= matrix_op_code; active_tensor <= matrix_tensor_id;
            active_expert <= matrix_expert_index; active_section <= 2'd0;
            active_q_beats <= matrix_q_beats; active_s_beats <= matrix_s_beats; active_z_beats <= matrix_z_beats;
            state <= LOOKUP_START;
          end
        end
        TOKEN_DMA_START: state <= TOKEN_STREAM;
        TOKEN_STREAM: if (dma_data_valid && dma_data_ready) begin
          token_id <= dma_data[active_token_byte_addr[3:2]*32 +: 9];
          state <= TOKEN_DONE;
        end
        TOKEN_DONE: state <= IDLE;
        LOOKUP_START: state <= LOOKUP_WAIT;
        LOOKUP_WAIT: begin
          if (desc_failed) begin error <= 1'b1; state <= FAIL; end
          else if (desc_found) begin
            if (active_is_matrix && desc_tensor_bytes != expected_bytes) begin error <= 1'b1; state <= FAIL; end
            else begin
              dma_base <= desc_tensor_addr;
              dma_bytes <= active_is_matrix ? expected_bytes : desc_tensor_bytes;
              small_beat <= '0;
              state <= DMA_START;
            end
          end
        end
        DMA_START: if (active_is_matrix) state <= MATRIX_STREAM; else state <= SMALL_STREAM;
        MATRIX_STREAM: if (dma_data_valid && dma_data_ready && dma_data_last) begin
          if (active_section == 2'd2) state <= IDLE;
          else begin active_section <= active_section + 1'b1; state <= LOOKUP_START; end
        end
        SMALL_STREAM: if (dma_data_valid && dma_data_ready) begin
          case (active_op)
            OP_L0_NORM1, OP_L0_NORM2, OP_L1_NORM1, OP_L1_NORM2, OP_FINAL_NORM:
              norm_offset_bus[small_beat*128 +: 128] <= dma_data;
            OP_L0_KDA: case (small_sub)
              3'd0: kda_q_taps_bus[small_beat*128 +: 128] <= dma_data;
              3'd1: kda_k_taps_bus[small_beat*128 +: 128] <= dma_data;
              default: kda_v_taps_bus[small_beat*128 +: 128] <= dma_data;
            endcase
            // The image stores router bias as eight signed Q4.11 int16
            // values. Expand every value into an independent DATA_W lane.
            OP_L0_MOE, OP_L1_MOE: if (small_beat == 0)
              for (lane = 0; lane < 8; lane = lane + 1)
                moe_bias_bus[lane*DATA_W +: DATA_W] <= {{(DATA_W-16){dma_data[lane*16+15]}}, dma_data[lane*16 +: 16]};
            OP_L0_RESMIX, OP_L1_RESA, OP_L1_RESMIX, OP_OUT_RESMIX: begin
              residual_score0 <= dma_data[DATA_W-1:0];
              residual_score1 <= dma_data[DATA_W +: DATA_W];
            end
            default: ;
          endcase
          if (dma_data_last) state <= NEXT_SMALL;
          else small_beat <= small_beat + 1'b1;
        end
        NEXT_SMALL: begin
          if (small_sub + 1 >= small_sub_count(active_op)) state <= SMALL_DONE;
          else begin small_sub <= small_sub + 1'b1; state <= LOOKUP_START; end
        end
        SMALL_DONE: state <= IDLE;
        FAIL: state <= IDLE;
        default: state <= IDLE;
      endcase
    end
  end
endmodule
